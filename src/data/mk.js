/* 행정구(또는 시) 1건 생성.
 *  dongs: [이름, 인접역/기준점, 랜드마크, 유형코드] — 랜드마크 생략 시 자동 보완 */
export const d = (name, geo, o = {}) => {
  const slug = o.slug || slugify(name.replace(/(구|군|시)$/, ''), { keepSuffix: true });
  return {
    slug, name,
    short: o.short || name,
    city: o.city || '',
    geo,
    lines: o.lines || [],
    hubs: o.hubs || [],
    marks: o.marks || [],
    zone: o.zone,
    near: o.near || [],
    night: o.night || '심야 수요 보통',
    road: o.road || '간선도로 접근 양호',
    dongs: (o.dongs || []).map(([dn, st, mk, type, s]) => {
      const pool = TRAITS[type] || TRAITS.resi;
      const dslug = s || slugify(dn);
      return {
        slug: dslug, name: dn,
        station: st,
        mark: mk || `${dn} 주민센터`,
        type: type || 'resi',
        trait: rng('trait:' + slug + dslug).pick(pool)
      };
    })
  };
};
